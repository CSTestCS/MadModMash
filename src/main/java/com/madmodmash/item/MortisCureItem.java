public class MortisCureItem extends DrinkItem {
    public MortisCureItem(Properties p) { super(p); }
    @Override protected void drink(ServerLevel level, Player p) { p.removeEffect(ModEffects.ZOMBIE_PLAGUE); p.removeEffect(MobEffects.HUNGER); p.heal(4); }
    @Override public InteractionResult interactLivingEntity(ItemStack stack, Player player, LivingEntity target, InteractionHand hand) {
        if (player.level() instanceof ServerLevel sl) {
            target.removeEffect(ModEffects.ZOMBIE_PLAGUE);
            if (target instanceof MortisZombie mz && mz.cure(sl, player)) { stack.shrink(1); return InteractionResult.SUCCESS; }
            stack.shrink(1);
        }
        return InteractionResult.SUCCESS;
    }
}
