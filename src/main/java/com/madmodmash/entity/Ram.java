/** Dark Adventures ram: neutral, charges anything that hurts it. Drops ram horns. */
public class Ram extends Animal {
    public Ram(EntityType<? extends Animal> type, Level level) { super(type, level); }
    public static AttributeSupplier.Builder createAttributes() {
        return Animal.createAnimalAttributes().add(Attributes.MAX_HEALTH, 16).add(Attributes.MOVEMENT_SPEED, 0.24).add(Attributes.ATTACK_DAMAGE, 5).add(Attributes.ATTACK_KNOCKBACK, 1.5);
    }
    @Override protected void registerGoals() {
        this.goalSelector.addGoal(0, new FloatGoal(this));
        this.goalSelector.addGoal(1, new MeleeAttackGoal(this, 1.5, true));
        this.goalSelector.addGoal(2, new BreedGoal(this, 1.0));
        this.goalSelector.addGoal(3, new TemptGoal(this, 1.2, s -> s.is(Items.WHEAT), false));
        this.goalSelector.addGoal(5, new WaterAvoidingRandomStrollGoal(this, 1.0));
        this.goalSelector.addGoal(6, new LookAtPlayerGoal(this, Player.class, 6F));
        this.targetSelector.addGoal(1, new HurtByTargetGoal(this));
    }
    @Override public boolean isFood(ItemStack s) { return s.is(Items.WHEAT); }
    @Override public AgeableMob getBreedOffspring(ServerLevel level, AgeableMob other) { return ModEntities.RAM.get().create(level, EntitySpawnReason.BREEDING); }
}
