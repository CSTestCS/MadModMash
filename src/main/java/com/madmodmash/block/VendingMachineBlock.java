/** Wutpak vending machine: one Silver Gildan per soda. */
public class VendingMachineBlock extends FacingBlock {
    public VendingMachineBlock(BlockBehaviour.Properties p) { super(p); }
    @Override protected InteractionResult useWithoutItem(BlockState state, Level level, BlockPos pos, Player player, BlockHitResult hit) {
        if (!(level instanceof ServerLevel sl)) return InteractionResult.SUCCESS;
        if (!Economy.pay(player, 9)) { player.sendOverlayMessage(Component.translatable("msg.madmodmash.vending_poor")); return InteractionResult.FAIL; }
        Item[] sodas = {ModItems.CREEPER_COLA.get(), ModItems.EMERALD_FIZZ.get(), ModItems.DOCTOR_BUBBLY.get()};
        Direction f = state.getValue(FACING);
        Util2.drop(sl, pos.getX() + 0.5 + f.getStepX() * 0.7, pos.getY() + 0.3, pos.getZ() + 0.5 + f.getStepZ() * 0.7, new ItemStack(sodas[sl.getRandom().nextInt(sodas.length)]));
        sl.playSound(null, pos, SoundEvents.DISPENSER_DISPENSE, SoundSource.BLOCKS, 1F, 1.2F);
        return InteractionResult.SUCCESS;
    }
}
